/**
 * Generates the plugins' config.properties (same keys, ranges and defaults as
 * apps/plugin-common/src/main/resources/config.properties) and installation
 * instructions. Runs in the browser: registration tokens never leave the page
 * except as a downloaded file.
 */
export type PluginKind = 'VELOCITY' | 'PAPER';

export const STATISTIC_CATEGORIES = ['movement', 'combat', 'blocks', 'general'] as const;
export type StatisticCategory = (typeof STATISTIC_CATEGORIES)[number];

export interface PluginConfigOptions {
  kind: PluginKind;
  backendUrl: string;
  registrationToken: string;
  language: string;
  debug: boolean;
  managedSettings: boolean;
  heartbeatIntervalSeconds: number;
  maxQueuedEvents: number;
  punishmentsEnabled: boolean;
  // Velocity
  collectIpAddresses: boolean;
  syncIntervalSeconds: number;
  moderationCommands: boolean;
  // Paper
  statisticsEnabled: boolean;
  statisticsIntervalSeconds: number;
  statisticsCategories: StatisticCategory[];
  afkTimeoutSeconds: number;
  inventorySync: boolean;
  enderChestSync: boolean;
  inventorySyncIntervalSeconds: number;
  anticheatIntegrations: string;
  anticheatMaxReportsPerMinute: number;
}

/** Allowed ranges; values outside are clamped by the plugin, so the form enforces them. */
export const RANGES = {
  heartbeatIntervalSeconds: [5, 300],
  syncIntervalSeconds: [15, 3600],
  maxQueuedEvents: [1_000, 1_000_000],
  statisticsIntervalSeconds: [60, 3600],
  afkTimeoutSeconds: [30, 3600],
  inventorySyncIntervalSeconds: [30, 3600],
  anticheatMaxReportsPerMinute: [1, 10_000],
} as const satisfies Record<string, readonly [number, number]>;

export function defaultOptions(kind: PluginKind, backendUrl: string): PluginConfigOptions {
  return {
    kind,
    backendUrl,
    registrationToken: '',
    language: 'en-US',
    debug: false,
    managedSettings: true,
    heartbeatIntervalSeconds: 15,
    maxQueuedEvents: 50_000,
    punishmentsEnabled: true,
    collectIpAddresses: true,
    syncIntervalSeconds: 60,
    moderationCommands: true,
    statisticsEnabled: true,
    statisticsIntervalSeconds: 300,
    statisticsCategories: [...STATISTIC_CATEGORIES],
    afkTimeoutSeconds: 300,
    inventorySync: true,
    enderChestSync: true,
    inventorySyncIntervalSeconds: 300,
    anticheatIntegrations: '',
    anticheatMaxReportsPerMinute: 120,
  };
}

export type ConfigProblem = 'backendUrl' | 'backendUrlPath' | 'integrations' | 'range';

/** Problems that would make the plugin refuse to start or behave unexpectedly. */
export function validateOptions(o: PluginConfigOptions): ConfigProblem[] {
  const problems: ConfigProblem[] = [];
  let url: URL | null = null;
  try {
    url = new URL(o.backendUrl);
  } catch {
    // reported below
  }
  if (!url || !['http:', 'https:'].includes(url.protocol)) problems.push('backendUrl');
  else if (url.pathname.replace(/\/$/, '') !== '' || url.search || url.hash) problems.push('backendUrlPath');
  if (o.anticheatIntegrations.split(',').some((n) => n.trim() && !/^[A-Za-z0-9_.-]{1,64}$/.test(n.trim()))) problems.push('integrations');
  for (const [key, [min, max]] of Object.entries(RANGES)) {
    const value = o[key as keyof typeof RANGES];
    if (!Number.isInteger(value) || value < min || value > max) {
      problems.push('range');
      break;
    }
  }
  return problems;
}

/** Plain HTTP to anything but a private address sends credentials-derived signatures in clear text. */
export function isInsecureUrl(backendUrl: string): boolean {
  try {
    const url = new URL(backendUrl);
    if (url.protocol !== 'http:') return false;
    const host = url.hostname;
    return !(host === 'localhost' || /^127\./.test(host) || /^10\./.test(host) || /^192\.168\./.test(host) || /^172\.(1[6-9]|2\d|3[01])\./.test(host) || host.endsWith('.local') || host.endsWith('.internal') || !host.includes('.'));
  } catch {
    return false;
  }
}

const normalizeUrl = (value: string) => value.trim().replace(/\/+$/, '');
const names = (value: string) =>
  [...new Set(value.split(',').map((n) => n.trim()).filter(Boolean))].join(',');
/** Properties values must not contain line breaks (they would start a new key). */
const single = (value: string) => value.replace(/[\r\n]+/g, ' ').trim();

export function generateConfig(o: PluginConfigOptions, generatedAt = new Date()): string {
  const paper = o.kind === 'PAPER';
  const lines: string[] = [
    '# ------------------------------------------------------------------',
    `# Nexora plugin configuration (${paper ? 'Paper' : 'Velocity'})`,
    `# Generated by the dashboard on ${generatedAt.toISOString()}`,
    '# ------------------------------------------------------------------',
    '',
    '# Address of the Nexora dashboard (the API is served under /api).',
    `backend-url=${single(normalizeUrl(o.backendUrl))}`,
    '',
    '# Single-use registration token. It is exchanged for credentials (credentials.properties)',
    '# on the first start and can be removed afterwards.',
    `registration-token=${single(o.registrationToken)}`,
    '',
    '# Language of plugin messages. Can be overridden in the dashboard (managed-settings).',
    `language=${single(o.language)}`,
    '',
    '# How often the server reports its status (5-300 seconds).',
    `heartbeat-interval-seconds=${o.heartbeatIntervalSeconds}`,
    '',
    '# Events kept in memory while the backend is unreachable.',
    `max-queued-events=${o.maxQueuedEvents}`,
    '',
    '# --- Moderation ------------------------------------------------------',
    `punishments-enabled=${o.punishmentsEnabled}`,
  ];
  if (!paper) {
    lines.push(
      `moderation-commands=${o.moderationCommands}`,
      '',
      '# --- Proxy ------------------------------------------------------------',
      '# Store player IP addresses with connection records (personal data).',
      `collect-ip-addresses=${o.collectIpAddresses}`,
      '# Full list of connected players sent periodically (15-3600 seconds).',
      `sync-interval-seconds=${o.syncIntervalSeconds}`,
    );
  } else {
    lines.push(
      '',
      '# --- Statistics ------------------------------------------------------',
      `statistics-enabled=${o.statisticsEnabled}`,
      `statistics-interval-seconds=${o.statisticsIntervalSeconds}`,
      `statistics-categories=${STATISTIC_CATEGORIES.filter((c) => o.statisticsCategories.includes(c)).join(',')}`,
      `afk-timeout-seconds=${o.afkTimeoutSeconds}`,
      '',
      '# --- AntiCheat integration -------------------------------------------',
      '# Plugins allowed to report violations (comma-separated plugin names). Empty = none.',
      `anticheat-integrations=${names(o.anticheatIntegrations)}`,
      `anticheat-max-reports-per-minute=${o.anticheatMaxReportsPerMinute}`,
      '',
      '# --- Inventories -----------------------------------------------------',
      `inventory-sync=${o.inventorySync}`,
      `enderchest-sync=${o.enderChestSync}`,
      `inventory-sync-interval-seconds=${o.inventorySyncIntervalSeconds}`,
    );
  }
  lines.push(
    '',
    '# --- Central management ------------------------------------------------',
    '# Let the dashboard override language, messages, statistics and inventory options live.',
    `managed-settings=${o.managedSettings}`,
    '',
    `debug=${o.debug}`,
    '',
  );
  return lines.join('\n');
}

/** Plugin data folder on the server (relative to the server directory). */
export function configPath(kind: PluginKind): string {
  return kind === 'VELOCITY' ? 'plugins/networkmanager/config.properties' : 'plugins/Nexora/config.properties';
}

export function jarName(kind: PluginKind, version: string): string {
  return `Nexora-${kind === 'VELOCITY' ? 'Velocity' : 'Paper'}-${version}.jar`;
}

/** Installation instructions shipped in the ZIP package (English, like all generated files). */
export function installGuide(o: PluginConfigOptions, serverName: string, version: string, expiresAt: string | null): string {
  const platform = o.kind === 'VELOCITY' ? 'Velocity proxy' : 'Paper server';
  const steps = [
    `# Nexora – ${platform} "${serverName}"`,
    '',
    '## Installation',
    '',
    `1. Stop the ${platform}.`,
    `2. Copy \`${jarName(o.kind, version)}\` into the \`plugins/\` folder (download it from https://github.com/epicclowds/Nexora/releases/tag/v${version}).`,
    `3. Copy \`config.properties\` from this package to \`${configPath(o.kind)}\`.`,
    `4. Start the ${platform}. The plugin registers itself and stores its credentials in \`credentials.properties\`.`,
    '5. Check the connection with `/networkmanager` in the console or in the dashboard under Servers.',
    '',
  ];
  if (o.registrationToken) {
    steps.push(
      '## Registration token',
      '',
      `The included token is single-use${expiresAt ? ` and expires at ${expiresAt}` : ''}. If it expired, create a new one in the dashboard (Settings → Minecraft integration).`,
      'Treat this package like a password until the server has registered.',
      '',
    );
  }
  steps.push(
    '## Notes',
    '',
    '- `managed-settings=true` lets the dashboard change language, messages, statistics and inventory options without a restart.',
    '- All other options in `config.properties` require a restart of the server.',
    '- Do not delete `credentials.properties` or `punishments-cache.json`.',
    '',
  );
  return steps.join('\n');
}
